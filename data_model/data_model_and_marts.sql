-- =====================================================================
-- SECTION 5: MART BUILD QUERIES (run after EVERY Gold load)
-- :from_key and :to_key are YYYYMMDD integers for the date range the load touched.
-- Pass them as query parameters (SQL editor / job parameters / notebook widgets),
-- or replace them with literal numbers, e.g. 20261025.
-- Each statement replaces only those dates, so reruns and late files never double-count.
