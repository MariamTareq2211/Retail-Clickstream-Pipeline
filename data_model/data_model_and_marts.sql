CREATE SCHEMA IF NOT EXISTS gold;

-- ===== DIMENSIONS =====

CREATE TABLE IF NOT EXISTS gold.dim_product (               -- SCD Type 2
  product_key      BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  product_id       BIGINT NOT NULL,                         -- business key; durable item id
  category_id      BIGINT,
  category_code    STRING NOT NULL,                         -- 'Unknown' when null
  category_level1  STRING NOT NULL,                         -- split of category_code
  category_level2  STRING NOT NULL,
  category_level3  STRING NOT NULL,
  brand            STRING NOT NULL,                         -- 'Unknown' when null
  base_price       DECIMAL(12,2),                           -- catalog price
  valid_from       TIMESTAMP NOT NULL,                      -- inclusive
  valid_to         TIMESTAMP NOT NULL,                      -- exclusive; 9999-12-31 23:59:59 = current
  is_current       BOOLEAN NOT NULL
) USING DELTA;

CREATE TABLE IF NOT EXISTS gold.dim_user (                  -- SCD Type 1
  user_key  BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  user_id   BIGINT NOT NULL                                 -- business key
) USING DELTA;

CREATE TABLE IF NOT EXISTS gold.dim_date (                  -- role-playing; static
  date_key          INT NOT NULL,                           -- YYYYMMDD
  full_date         DATE NOT NULL,
  year              INT NOT NULL,
  quarter           INT NOT NULL,
  month             INT NOT NULL,
  month_name        STRING NOT NULL,
  day               INT NOT NULL,
  day_of_week_num   INT NOT NULL,                           -- 1 = Monday ... 7 = Sunday (sort key)
  day_of_week       STRING NOT NULL,
  iso_week          INT NOT NULL,
  is_weekend        BOOLEAN NOT NULL,
  is_seasonal_peak  BOOLEAN NOT NULL                        -- natural peaks only (e.g. Black Friday); never the injected surge
) USING DELTA;

CREATE TABLE IF NOT EXISTS gold.dim_time (                  -- role-playing; static
  time_key       INT NOT NULL,                              -- seconds since midnight, 0-86399
  full_time      STRING NOT NULL,                           -- HH:mm:ss
  hour           INT NOT NULL,
  minute         INT NOT NULL,
  second         INT NOT NULL,
  time_category  STRING NOT NULL                            -- Morning, Peak, Evening, Night
) USING DELTA;

CREATE TABLE IF NOT EXISTS gold.dim_platform (
  platform_key   INT NOT NULL,                              -- 1 web, 2 mobile
  platform_name  STRING NOT NULL
) USING DELTA;

CREATE TABLE IF NOT EXISTS gold.dim_marketing_channel (
  channel_key    INT NOT NULL,                              -- 1 organic, 2 paid, 3 email, 4 social
  channel_name   STRING NOT NULL
) USING DELTA;

CREATE TABLE IF NOT EXISTS gold.dim_event_type (
  event_type_key   INT NOT NULL,                            -- 1 view, 2 cart, 3 remove_from_cart, 4 purchase
  event_type_name  STRING NOT NULL
) USING DELTA;

-- ===== FACTS =====

CREATE TABLE IF NOT EXISTS gold.fact_events (               -- grain: one deduplicated event
  event_id                 STRING NOT NULL,                 -- hash(user_session, event_time, event_type, product_id)
  user_session             STRING NOT NULL,                 -- degenerate dimension
  session_key              BIGINT NOT NULL,                 -- xxhash64(user_session)
  event_ts                 TIMESTAMP NOT NULL,              -- replay clock
  source_event_ts          TIMESTAMP NOT NULL,              -- original REES46 time
  ingestion_ts             TIMESTAMP NOT NULL,
  product_key              BIGINT NOT NULL,                 -- version valid at event_ts
  product_id               BIGINT NOT NULL,                 -- durable key
  user_key                 BIGINT NOT NULL,
  event_type_key           INT NOT NULL,
  event_date_key           INT NOT NULL,
  event_time_key           INT NOT NULL,
  ingestion_date_key       INT NOT NULL,
  ingestion_time_key       INT NOT NULL,
  platform_key             INT NOT NULL,
  channel_key              INT NOT NULL,
  is_bot                   INT NOT NULL,                    -- 0/1, copied from the session
  event_price              DECIMAL(12,2) NOT NULL,          -- non-additive
  revenue                  DECIMAL(12,2) NOT NULL,          -- event_price on purchase, else 0
  event_count              INT NOT NULL,                    -- always 1
  ingestion_delay_seconds  INT NOT NULL                     -- ingestion_ts - event_ts
) USING DELTA
PARTITIONED BY (event_date_key);

CREATE TABLE IF NOT EXISTS gold.fact_sessions (             -- grain: one session; accumulating snapshot
  session_key                 BIGINT NOT NULL,              -- xxhash64(user_session)
  user_session                STRING NOT NULL,
  user_key                    BIGINT NOT NULL,
  session_start_date_key      INT NOT NULL,
  session_start_time_key      INT NOT NULL,
  platform_key                INT NOT NULL,
  channel_key                 INT NOT NULL,
  session_start_ts            TIMESTAMP NOT NULL,
  session_end_ts              TIMESTAMP NOT NULL,
  is_bot                      INT NOT NULL,
  is_first_session            INT NOT NULL,
  is_impossible_sequence      INT NOT NULL,
  has_view                    INT NOT NULL,
  has_cart                    INT NOT NULL,
  has_purchase                INT NOT NULL,
  view_count                  INT NOT NULL,
  cart_count                  INT NOT NULL,
  purchase_count              INT NOT NULL,
  events_per_session          INT NOT NULL,
  session_duration_seconds    INT NOT NULL,                 -- 0 for a single-event session
  time_to_first_cart_seconds  INT,                          -- null when no cart
  session_cart_value          DECIMAL(12,2) NOT NULL,
  session_revenue             DECIMAL(12,2) NOT NULL,
  last_updated_ts             TIMESTAMP NOT NULL
) USING DELTA
PARTITIONED BY (session_start_date_key);


