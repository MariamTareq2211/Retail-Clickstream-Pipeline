-- Mart 1: Executive & Marketing
INSERT INTO gold.mart_executive_marketing REPLACE WHERE date_key BETWEEN 20190101 AND 20301231
SELECT session_start_date_key, platform_key, channel_key,
       COUNT(*),
       SUM(has_purchase),
       SUM(session_revenue),
       SUM(view_count),
       SUM(purchase_count),
       SUM(CASE WHEN is_first_session = 1 THEN 1 ELSE 0 END),
       SUM(CASE WHEN is_first_session = 0 THEN 1 ELSE 0 END)
FROM gold.fact_sessions
WHERE is_bot = 0 AND session_start_date_key BETWEEN 20190101 AND 20301231
GROUP BY session_start_date_key, platform_key, channel_key;

-- Mart 2: Funnel & Behavior (funnel population: has_view = 1)
INSERT INTO gold.mart_funnel_behavior REPLACE WHERE date_key BETWEEN 20190101 AND 20301231
SELECT session_start_date_key, platform_key, channel_key,
       SUM(has_view),
       SUM(CASE WHEN has_view = 1 AND has_cart = 1 THEN 1 ELSE 0 END),
       SUM(CASE WHEN has_view = 1 AND has_purchase = 1 THEN 1 ELSE 0 END),
       SUM(CASE WHEN has_view = 1 AND has_cart = 1 AND has_purchase = 0 THEN 1 ELSE 0 END),
       SUM(CASE WHEN has_view = 0 THEN 1 ELSE 0 END),
       SUM(CASE WHEN has_view = 1 AND has_cart = 1 AND has_purchase = 0 THEN session_cart_value ELSE 0 END),
       SUM(CASE WHEN has_view = 1 THEN session_duration_seconds ELSE 0 END),
       SUM(CASE WHEN has_view = 1 THEN events_per_session ELSE 0 END),
       SUM(CASE WHEN has_view = 1 AND has_cart = 1 THEN COALESCE(time_to_first_cart_seconds, 0) ELSE 0 END)
FROM gold.fact_sessions
WHERE is_bot = 0 AND session_start_date_key BETWEEN 20190101 AND 20301231
GROUP BY session_start_date_key, platform_key, channel_key;

-- Mart 3: Product & Brand Performance
INSERT INTO gold.mart_product_brand_performance REPLACE WHERE date_key BETWEEN 20190101 AND 20301231
WITH band AS (
  SELECT product_id,
         CASE ntile(3) OVER (ORDER BY avg_price)
              WHEN 1 THEN 'Low' WHEN 2 THEN 'Mid' ELSE 'High' END AS price_band
  FROM (SELECT product_id, AVG(event_price) AS avg_price
        FROM gold.fact_events
        WHERE is_bot = 0 AND event_type_key = 1
        GROUP BY product_id)
)
SELECT e.event_date_key, e.platform_key, e.channel_key, e.product_key,
       SUM(CASE WHEN e.event_type_key = 1 THEN 1 ELSE 0 END),
       SUM(CASE WHEN e.event_type_key = 2 THEN 1 ELSE 0 END),
       SUM(CASE WHEN e.event_type_key = 4 THEN 1 ELSE 0 END),
       SUM(e.revenue),
       SUM(CASE WHEN e.event_type_key = 1 THEN e.event_price ELSE 0 END),
       COALESCE(b.price_band, 'Unknown')
FROM gold.fact_events e
LEFT JOIN band b ON b.product_id = e.product_id
WHERE e.is_bot = 0 AND e.event_date_key BETWEEN 20190101 AND 20301231
GROUP BY e.event_date_key, e.platform_key, e.channel_key, e.product_key,
         COALESCE(b.price_band, 'Unknown');

-- Price bands depend on the whole product mix: after a large load, rerun Mart 3
